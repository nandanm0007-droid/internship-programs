def addnum(n1, n2):
    sum = n1 + n2
    print(sum)

def subnum(n1, n2):
    sub = n1 - n2
    print(sub)

def mulnum(n1, n2):
    pro = n1 * n2
    print(pro)

def divnum(n1, n2):
    div = n1 / n2
    print(div)

num1 = int(input("enter first number"))
num2 = int(input("enter second number"))

addnum(num1, num2)
subnum(num1, num2)
mulnum(num1, num2)
divnum(num1, num2)